// gradeByScore 将分数映射为等级。
func gradeByScore(v int) string {
	switch {
	case v >= 90:
		return "上上"
	case v >= 80:
		return "上"
	case v >= 70:
		return "中上"
	case v >= 60:
		return "中"
	case v >= 45:
		return "中下"
	default:
		return "下"
	}
}