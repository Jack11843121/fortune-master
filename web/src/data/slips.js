// 今日黄历（仅用于算乐游戏点缀）
export function huangliToday() {
  const d = new Date()
  const n = d.getFullYear() * 10000 + (d.getMonth() + 1) * 100 + d.getDate()
  return { yi: YI[n % YI.length], ji: JI[(n >>> 1) % JI.length] }
}

export function randomSlip() {
  return SLIPS[Math.floor(Math.random() * SLIPS.length)]
}

export function dailySlip() {
  const d = new Date()
  const n = d.getFullYear() * 10000 + (d.getMonth() + 1) * 100 + d.getDate()
  return SLIPS[n % SLIPS.length]
}